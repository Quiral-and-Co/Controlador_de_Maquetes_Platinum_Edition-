const assert=require('node:assert/strict');
const traffic=require('../traffic-core.js');
const state=traffic.createState();
assert.equal(traffic.validateAddress('3','S').ok,true);
assert.equal(traffic.validateAddress('128','L').ok,true);
assert.equal(traffic.validateAddress('128','S').ok,false);
assert.equal(traffic.validateAddress('127','L').ok,false);
assert.equal(traffic.addLocomotive(state,{id:'L1',name:'Märklin BR 01',address:'1234',addressType:'L'}).ok,true);
assert.equal(traffic.addLocomotive(state,{id:'L2',name:'Duplicate',address:'1234',addressType:'L'}).ok,false);
const routes=[{id:'R1',name:'Estació a estació',blockIds:['B01','B02','B03']}];
const created=traffic.createRun(state,{locomotiveId:'L1',routeId:'R1',mode:'AUTO',maxSpeed:90},routes);
assert.equal(created.ok,true);
assert.equal(created.run.maxSpeed,20,'automatic mode has a hard speed-step ceiling');
const run=created.run;
const snapshot={blockStates:{B01:'OCCUPIED',B02:'FREE',B03:'FREE'},reservations:{}};
const safe={jmriConnected:true,jmriPower:'ON',bridgeConnected:true,dccArmed:true,sensorDataValid:true,hasUnverifiedTurnouts:false};
assert.equal(traffic.preflight(run,routes[0],snapshot,{...safe,jmriPower:'UNKNOWN'}).ok,false,'unknown power blocks start');
assert.equal(traffic.preflight(run,routes[0],{...snapshot,blockStates:{...snapshot.blockStates,B02:'UNKNOWN'}},safe).ok,false,'unknown next block blocks start');
assert.equal(traffic.preflight(run,routes[0],snapshot,{...safe,hasUnverifiedTurnouts:true}).ok,false,'automatic route with turnout is blocked');
assert.equal(traffic.preflight(run,routes[0],snapshot,safe).ok,true);
assert.equal(traffic.startRun(run).ok,true);
let result=traffic.evaluateAutomatic(run,routes[0],{B01:'OCCUPIED',B02:'OCCUPIED',B03:'FREE'},1000);
assert.deepEqual(result,{action:'ADVANCE',block:'B02'});
assert.equal(run.currentIndex,1);
result=traffic.evaluateAutomatic(run,routes[0],{B01:'OCCUPIED',B02:'OCCUPIED',B03:'FREE'},2000);
assert.equal(result.action,'NONE','wait while previous block remains occupied');
result=traffic.evaluateAutomatic(run,routes[0],{B01:'FREE',B02:'OCCUPIED',B03:'OCCUPIED'},3000);
assert.deepEqual(result,{action:'ADVANCE',block:'B03'});
result=traffic.evaluateAutomatic(run,routes[0],{B01:'FREE',B02:'FREE',B03:'OCCUPIED'},4000);
assert.equal(result.action,'STOP');
assert.equal(run.status,'ARRIVED');
assert.equal(traffic.completeRun(run,routes[0],{B01:'FREE',B02:'FREE',B03:'OCCUPIED'}).ok,false,'keep reservation until final block is confirmed free');
assert.equal(traffic.completeRun(run,routes[0],{B01:'FREE',B02:'FREE',B03:'FREE'}).ok,true);
const state2=traffic.createState();
traffic.addLocomotive(state2,{id:'L1',name:'Test',address:'12',addressType:'S'});
const run2=traffic.createRun(state2,{locomotiveId:'L1',routeId:'R1',mode:'AUTO'},routes).run;
traffic.startRun(run2);
result=traffic.evaluateAutomatic(run2,routes[0],{B01:'UNKNOWN',B02:'FREE',B03:'FREE'},1000);
assert.deepEqual(result,{action:'STOP',reason:'Pèrdua de lectura del bloc actual.'});
assert.equal(traffic.stopRun(run2,'sensor lost').status,'FAULT');
assert.equal(traffic.createRun(state2,{locomotiveId:'L1',routeId:'R1',mode:'MANUAL'},routes).ok,false,'faulted route and loco remain locked');
console.log('PASS: Märklin DCC address validation, traffic preflight, automatic block progression, fail-safe stops and route release');
