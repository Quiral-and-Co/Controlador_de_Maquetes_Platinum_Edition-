const assert=require('node:assert/strict');
const core=require('../physical-validation-core.js');
const config={signals:[{id:'S1',name:'Entrada'}],levels:[{id:1,name:'Nivell 1',blocks:[{id:'B1'}],sensors:[{id:'SN1',systemName:'LS1'}],tracks:[{id:'T1',type:'turnout',turnoutSystemName:'LT1'}]}]};
let result=core.inspect(config);
assert.equal(result.counts.total,4);
assert.equal(result.counts.pendingSoftware,4);
const signalKey=core.key('signal','S1');
for(const c of core.CHECKS.signal.filter(x=>x.kind==='software'))assert.equal(core.setCheck(config,signalKey,c.id,true,10).ok,true);
result=core.inspect(config);assert.equal(result.entries.find(x=>x.key===signalKey).status,'SOFTWARE_READY');
for(const c of core.CHECKS.signal.filter(x=>x.kind==='physical'))core.setCheck(config,signalKey,c.id,true,20);
result=core.inspect(config);assert.equal(result.entries.find(x=>x.key===signalKey).status,'PHYSICAL_READY');
assert.equal(core.setFailure(config,signalKey,true,'Cablejat incorrecte',30).ok,true);
result=core.inspect(config);assert.equal(result.entries.find(x=>x.key===signalKey).status,'FAILED');
assert.equal(result.entries.find(x=>x.key===signalKey).failureReason,'Cablejat incorrecte');
core.setFailure(config,signalKey,false,'',40);
assert.equal(core.inspect(config).entries.find(x=>x.key===signalKey).status,'PHYSICAL_READY');
assert.equal(core.setCheck(config,'signal:MISSING','software-link',true).ok,false);
assert.equal(core.setCheck(config,signalKey,'unknown',true).ok,false);
const levels=core.levelDiagnostics(config,{});
assert.equal(levels[0].entities,3);
assert.equal(levels[0].failed,0);
console.log('PASS: per-entity physical validation matrix');
