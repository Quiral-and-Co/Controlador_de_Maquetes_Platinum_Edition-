const assert=require('node:assert/strict');
const vmr=require('../validation-master-registry-core.js');
const physical=require('../physical-validation-core.js');
const makeConfig=name=>({name,signals:[{id:'S1',name:'Entrada'}],levels:[{id:1,name:'Nivell 1',blocks:[{id:'B1'}],sensors:[{id:'SN1',systemName:'LS1'}],tracks:[{id:'T1',type:'turnout',turnoutSystemName:'LT1'}]}]});
const config=makeConfig('Projecte compartit');
const projectId=vmr.ensureProjectId(config,()=> 'project-A');
assert.equal(projectId,'project-A');
const s=vmr.createState({projectId});
assert.equal(vmr.reconcile(s,config,1000).length,4);
assert.equal(new Set(s.records.map(r=>r.registryId)).size,4);
assert.match(s.records[0].registryId,/^JMRI-TC-VMR-/);
vmr.reconcile(s,config,2000);
assert.equal(s.records.length,4);
vmr.updateValidation(s,config,physical,3000);
assert.equal(s.records.every(r=>r.status==='PENDING_SOFTWARE'),true);
const storage={data:{},getItem(k){return this.data[k]||null;},setItem(k,v){this.data[k]=v;}};
const keyA=vmr.storageKey(projectId);
assert.equal(vmr.save(s,storage,keyA).ok,true);
const id=s.records[0].registryId;
assert.equal(vmr.appendNote(s,id,'Inspecció visual pendent','tester',4000).ok,true);
assert.equal(vmr.save(s,storage,keyA).ok,true);
assert.equal(vmr.appendNote(s,'missing','x').ok,false);
const projectExport=JSON.stringify({...config,projectId,validationMasterRegistry:s});
const reloadedProject=JSON.parse(projectExport);
const restartedStorage={data:{...storage.data},getItem(k){return this.data[k]||null;},setItem(k,v){this.data[k]=v;}};
const afterReload=vmr.createState(reloadedProject.validationMasterRegistry||vmr.load(restartedStorage,vmr.storageKey(reloadedProject.projectId)));
assert.equal(afterReload.projectId,'project-A');
assert.equal(afterReload.records.length,4);
assert.equal(afterReload.records.find(r=>r.registryId===id).notes[0].text,'Inspecció visual pendent');
assert.equal(afterReload.audit.length,s.audit.length);
delete reloadedProject.validationMasterRegistry.counters;
const recovered=vmr.createState(reloadedProject.validationMasterRegistry);
const next=vmr.reconcile(recovered,{...config,signals:[{id:'S2',name:'Sortida'}]},7000);
assert.equal(next.length,1);
assert.equal(next[0].registryId,'JMRI-TC-VMR-SIGNAL-00002');
assert.equal(recovered.records.filter(r=>r.registryId===next[0].registryId).length,1);
// Two projects with identical names must get isolated identifiers and storage.
const projectB=makeConfig('Projecte compartit');
const projectBId=vmr.ensureProjectId(projectB,()=> 'project-B');
assert.notEqual(projectBId,projectId);
const keyB=vmr.storageKey(projectBId);
assert.notEqual(keyA,keyB);
const stateB=vmr.createState({projectId:projectBId});
vmr.reconcile(stateB,projectB,8000);
assert.equal(vmr.save(stateB,restartedStorage,keyB).ok,true);
assert.equal(vmr.load(restartedStorage,keyA).records.length,4);
assert.equal(vmr.load(restartedStorage,keyB).records.length,4);
const act=vmr.buildAct(s,config,{now:5000});
assert.match(act.id,/^JMRI-TC-VMR-ACT-/);
assert.match(act.markdown,/DCC, sortides físiques/);
assert.match(act.markdown,/Historial d’auditoria/);
assert.match(act.markdown,/Inspecció visual pendent/);
assert.equal(act.counts.total,4);
const act2=vmr.buildAct(s,config,{now:5000});
assert.notEqual(act2.id,act.id,'consecutive acts must have unique IDs even for identical timestamps and audit lengths');
assert.equal(JSON.parse(JSON.stringify(act)).entries.length,4);
config.signals=[];
vmr.reconcile(s,config,9000);
assert.equal(s.records.find(r=>r.type==='signal').present,false);
console.log('PASS: VMR project isolation, reload persistence, stable IDs, audit and unique validation acts');
