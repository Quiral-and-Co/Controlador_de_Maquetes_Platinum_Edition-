const assert = require('node:assert/strict');
const viewport = require('../viewport-core.js');
const board = { width: 3000, height: 1800 };
const full = viewport.fit(board);
assert.deepEqual(full, { x: 0, y: 0, width: 3000, height: 1800 });
assert.equal(viewport.zoomPercent(full, board), 100);
const anchor = { x: 1000, y: 600 }, close = viewport.zoomAt(full, 0.5, anchor, board);
assert.deepEqual(close, { x: 500, y: 300, width: 1500, height: 900 });
assert.equal(viewport.zoomPercent(close, board), 200);
assert.ok(Math.abs((anchor.x - close.x) / close.width - 1 / 3) < 1e-12, 'zoom must preserve horizontal anchor');
assert.ok(Math.abs((anchor.y - close.y) / close.height - 1 / 3) < 1e-12, 'zoom must preserve vertical anchor');
const moved = viewport.panBy(close, 500, 400, board); assert.deepEqual(moved, { x: 1000, y: 700, width: 1500, height: 900 });
const back = viewport.panBy(moved, -500, -400, board); assert.deepEqual(back, close);
const farther = viewport.panBy(close, 10000, 10000, board); assert.deepEqual(farther, { x: 1500, y: 900, width: 1500, height: 900 });
const zoomedOut = viewport.zoomAt(full, 2, { x: 1500, y: 900 }, board); assert.deepEqual(zoomedOut, { x: -1500, y: -900, width: 6000, height: 3600 });
const minZoom = viewport.zoomAt(full, 0.001, { x: 0, y: 0 }, board); assert.equal(minZoom.width, 300); assert.equal(minZoom.height, 180);
const maxZoom = viewport.zoomAt(full, 100, { x: 1500, y: 900 }, board); assert.equal(maxZoom.width, 6000);
assert.throws(() => viewport.zoomAt(full, 0, anchor, board), /factor/);
assert.throws(() => viewport.panBy(full, Infinity, 0, board), /finit/);
assert.throws(() => viewport.fit({ width: 0, height: 1800 }), /positives/);
console.log('PASS: viewport fit, cursor-anchored zoom, zoom limits, bounded panning and invalid-input guards');
