'use strict';
const assert=require('node:assert/strict');
const core=require('../jmri-turnout-supervision-core.js');
const dispatcherCore=require('../dispatcher-core.js');
const now=100000;
const route={id:'R1',name:'Ruta nord',blockIds:['B1','B2'],turnoutRequirements:[{systemName:'LT1',requiredState:'CLOSED'},{systemName:'LT2',requiredState:'THROWN'}]};
const config={levels:[]};
const accessories=[{type:'TURNOUT',systemName:'LT1',verified:true},{type:'TURNOUT',systemName:'LT2',verified:true}];
const telemetry={connected:true,lastHeartbeatAt:now,turnouts:{LT1:2,LT2:4},turnoutUpdatedAt:{LT1:now,LT2:now}};
let result=core.inspectRoute(route,config,telemetry,accessories,now);
assert.equal(result.ok,true,'fresh verified turnouts aligned with route requirements');
assert.equal(result.status,'ALIGNED');
result=core.inspectRoute(route,config,{...telemetry,turnouts:{LT1:4,LT2:4}},accessories,now);
assert.equal(result.ok,false,'misaligned turnout blocks route');
assert.equal(result.status,'MISALIGNED');
assert.ok(result.incidents.some(x=>x.code==='TURNOUT_MISALIGNED'));
result=core.inspectRoute(route,config,{...telemetry,connected:false},accessories,now);
assert.equal(result.ok,false,'communication loss blocks route');
assert.ok(result.incidents.some(x=>x.code==='JMRI_DISCONNECTED'));
assert.ok(result.incidents.some(x=>x.code==='TURNOUT_UNKNOWN'));
result=core.inspectRoute(route,config,{...telemetry,turnoutUpdatedAt:{LT1:now-20000,LT2:now}},accessories,now);
assert.equal(result.ok,false,'stale feedback is unknown');
assert.ok(result.incidents.some(x=>x.code==='TURNOUT_UNKNOWN'));
result=core.inspectRoute(route,config,telemetry,[{...accessories[0],verified:false},accessories[1]],now);
assert.equal(result.ok,false,'unverified turnout blocks route');
assert.ok(result.incidents.some(x=>x.code==='TURNOUT_UNVERIFIED'));
result=core.inspectRoute(route,config,{...telemetry,turnouts:{LT1:99,LT2:4}},accessories,now);
assert.equal(result.ok,false,'invalid feedback blocks route');
assert.ok(result.incidents.some(x=>x.code==='TURNOUT_INVALID'));
result=core.inspectRoute({ ...route,turnoutRequirements:[{systemName:'LT1'}]},config,telemetry,accessories,now);
assert.equal(result.ok,false,'missing required position blocks route');
assert.ok(result.incidents.some(x=>x.code==='TURNOUT_REQUIREMENT_MISSING'));
const layoutRoute={id:'R2',name:'Route via turnout',blockIds:['B3']};
const layout={levels:[{tracks:[{id:'T1',type:'turnout',blockId:'B3',turnoutSystemName:'LT3'}]}]};
result=core.inspectRoute(layoutRoute,layout,{...telemetry,turnouts:{...telemetry.turnouts,LT3:2},turnoutUpdatedAt:{...telemetry.turnoutUpdatedAt,LT3:now}},[...accessories,{type:'TURNOUT',systemName:'LT3',verified:true}],now);
assert.equal(result.ok,false,'a turnout in a route block without explicit required position fails closed');
assert.ok(result.incidents.some(x=>x.code==='TURNOUT_REQUIREMENT_MISSING'));
result=core.inspectRoute(route,config,telemetry,accessories,now);
assert.equal(result.ok,true,'fresh aligned feedback restores the diagnostic state after recovery');
assert.equal(result.status,'ALIGNED','recovery is observed, not an automatic movement or reservation');
assert.equal(core.normalizePosition(0),'UNKNOWN');
assert.equal(core.normalizeExpected('4'),'THROWN');
const initialLabel='Desviament · recte';
const once=core.supervisionAriaLabel(initialLabel,'ALIGNED');
const twice=core.supervisionAriaLabel(once,'ALIGNED');
const afterTransition=core.supervisionAriaLabel(once,'MISALIGNED');
assert.equal(once,'Desviament · recte · supervisió ALIGNED');
assert.equal(twice,once,'repeated SVG refreshes must not append duplicate accessibility labels');
assert.equal(afterTransition,'Desviament · recte · supervisió MISALIGNED','state changes replace the prior accessible status');
const dispatcherState=dispatcherCore.createState();
dispatcherCore.setRoutes(dispatcherState,[route]);
assert.deepEqual(dispatcherState.routes[0].turnoutRequirements,route.turnoutRequirements,'Dispatcher route normalization preserves required turnout positions');
console.log('PASS: turnout alignment, stale feedback, communication loss, verification, invalid states, stable SVG accessibility labels, Dispatcher route persistence and safe recovery');
